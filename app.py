def predict_retina(image):

    global session_results

    if image is None:

        return (
            "⚠️ Please upload or capture a retinal image."
        )

    image = image.convert("RGB")

    tensor = transform(
        image
    ).unsqueeze(0).to(DEVICE)

    with torch.no_grad():

        logits = model(
            tensor
        )

        probabilities = torch.sigmoid(
            logits
        )[0].cpu().numpy()

    results = []

    for index, probability in enumerate(
        probabilities
    ):

        results.append({

            "index": index,

            "condition":
                disease_labels[index],

            "probability":
                float(probability)

        })

    results.sort(
        key=lambda x: x["probability"],
        reverse=True
    )

    session_results = results

    text = """
# 🧠 AI Screening Result

### Detected retinal conditions / abnormalities

"""

    for result in results[:10]:

        percentage = (
            result["probability"] * 100
        )

        text += (
            f"**{result['condition']}**  \n"
            f"Confidence: **{percentage:.2f}%**\n\n"
        )

    text += """
---

### ⚠️ Screening Notice

This result is generated by an AI screening model.
It is **not a medical diagnosis** and should be
reviewed by a qualified eye-care professional.
"""

    return text


