def generate_gradcam(image):

    if image is None:
        return None

    if not session_results:
        return None

    target_index = session_results[0]["index"]

    model.eval()

    img = image.convert("RGB")

    tensor = transform(
        img
    ).unsqueeze(0).to(DEVICE)

    activations = []
    gradients = []

    target_layer = model.features[-1]

    def forward_hook(
        module,
        input,
        output
    ):

        activations.append(
            output
        )

    def backward_hook(
        module,
        grad_input,
        grad_output
    ):

        gradients.append(
            grad_output[0]
        )

    forward_handle = (
        target_layer.register_forward_hook(
            forward_hook
        )
    )

    backward_handle = (
        target_layer.register_full_backward_hook(
            backward_hook
        )
    )

    try:

        output = model(
            tensor
        )

        target_score = output[
            0,
            target_index
        ]

        model.zero_grad()

        target_score.backward()

        activation = (
            activations[0].detach()
        )

        gradient = (
            gradients[0].detach()
        )

        weights = gradient.mean(
            dim=(2, 3),
            keepdim=True
        )

        cam = (
            weights * activation
        ).sum(dim=1)

        cam = F.relu(
            cam
        )

        cam = (
            cam[0]
            .cpu()
            .numpy()
        )

        if cam.max() > 0:

            cam = (
                cam / cam.max()
            )

        original = np.array(
            img
        )

        import cv2

        heatmap = cv2.resize(

            cam,

            (
                original.shape[1],
                original.shape[0]
            )
        )

        heatmap = np.uint8(
            255 * heatmap
        )

        heatmap = cv2.applyColorMap(

            heatmap,

            cv2.COLORMAP_JET
        )

        heatmap = cv2.cvtColor(

            heatmap,

            cv2.COLOR_BGR2RGB
        )

        overlay = (

            0.55 * original
            +
            0.45 * heatmap

        ).clip(
            0,
            255
        ).astype(
            np.uint8
        )

        # Label the two panels

        import PIL.ImageDraw as ImageDraw
        import PIL.ImageFont as ImageFont

        combined = np.hstack(
            [
                original,
                overlay
            ]
        )

        result_image = Image.fromarray(
            combined
        )

        return result_image

    finally:

        forward_handle.remove()
        backward_handle.remove()


